// 1. routes: every page of the Next.js app directory
function routes() {
  const base = path.join(FRONT, "src", "app");
  const out = [];
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name === "page.tsx") out.push(path.relative(base, dir));
    }
  };
  walk(base);
  const pages = out
    .map((rel) => ({ rel, route: "/" + rel.split(path.sep).filter((s) => !s.startsWith("(")).join("/") }))
    .filter((r) => r.route !== "/" && !r.route.startsWith("/login"))
    .sort((a, b) => b.route.split("/").length - a.route.split("/").length || a.route.localeCompare(b.route));
  const imports = pages.map((p, i) => `import P${i} from "@/app/${p.rel.split(path.sep).join("/")}/page";`).join("\n");
  const table = pages.map((p, i) => `  [${JSON.stringify(p.route)}, P${i}],`).join("\n");
  fs.writeFileSync(
    path.join(HERE, "spa", "routes.ts"),
    `// Generated by build.mjs from frontend/src/app — do not edit.
import type { ComponentType } from "react";
${imports}

const ROUTES: [string, ComponentType][] = [
${table}
];

function match(pattern: string, pathname: string): Record<string, string> | null {
  const a = pattern.split("/");
  const b = pathname.split("/");
  if (a.length !== b.length) return null;
  const params: Record<string, string> = {};
  for (let i = 0; i < a.length; i++) {
    if (a[i].startsWith("[") && a[i].endsWith("]")) params[a[i].slice(1, -1)] = decodeURIComponent(b[i]);
    else if (a[i] !== b[i]) return null;
  }
  return params;
}

export function resolveRoute(pathname: string): ComponentType {
  for (const [pattern, page] of ROUTES) if (match(pattern, pathname)) return page;
  return ROUTES.find(([p]) => p === "/dashboard")![1];
}

export function matchParams(pathname: string): Record<string, string> {
  for (const [pattern] of ROUTES) {
    const m = match(pattern, pathname);
    if (m) return m;
  }
  return {};
}
`,
  );
  return pages.length;
}
console.log(`routes: ${routes()} pages`);

// 2. fonts: Latin subsets of the app's self-hosted fonts, embedded
function fontsCss() {
  const sources = [
    path.join(FRONT, "node_modules/@fontsource-variable/inter/index.css"),
    path.join(FRONT, "node_modules/@fontsource/ibm-plex-mono/400.css"),
    path.join(FRONT, "node_modules/@fontsource/ibm-plex-mono/500.css"),
  ];
  let css = "";
  for (const file of sources) {
    const text = fs.readFileSync(file, "utf8");
    for (const block of text.split(/(?=\/\*)/)) {
      const name = (block.match(/\/\*\s*([^*]+?)\s*\*\//) || [])[1] || "";
      if (!/-latin-/.test(name)) continue;
      css += block.replace(/url\(\.\/files\/([^)]+)\)/g, (_, f) => {
        const buf = fs.readFileSync(path.join(path.dirname(file), "files", f));
        return `url(data:font/woff2;base64,${buf.toString("base64")})`;
      });
    }
  }
  return css;
}

// 3. Tailwind: the app's own globals.css, compiled against the app sources
async function tailwindCss() {
  const req = (await import("node:module")).createRequire(path.join(FRONT, "package.json"));
  const postcss = req("postcss");
  const tailwind = req("@tailwindcss/postcss");
  const from = path.join(FRONT, "src", "app", "globals.css");
  const res = await postcss([tailwind({ base: path.join(FRONT, "src"), optimize: { minify: true } })]).process(fs.readFileSync(from, "utf8"), { from });
  return res.css;
}


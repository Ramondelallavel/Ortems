// Builds the MonxuPlan browser edition into ./dist:
//
//   dist/index.html          the page (inline CSS + JS: the web app's pages, router and API bridge)
//   dist/backend-worker.js   Web Worker hosting the Python API
//   dist/py/*.json           Python standard library, MonxuPlan backend and its dependencies (JSON bundles)
//   dist/pyodide/…           the Pyodide runtime (CPython compiled to WebAssembly)
//
// Usage: npm install && node build.mjs   (needs python3 + pip for the wheels)
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const FRONT = path.join(ROOT, "frontend");
const DIST = path.join(HERE, "dist");
const CACHE = path.join(HERE, ".cache");
const PYODIDE = path.join(HERE, "node_modules", "pyodide");
const PYODIDE_FILES = ["pyodide.mjs", "pyodide.asm.mjs", "pyodide.asm.wasm", "pyodide-lock.json"];

fs.rmSync(DIST, { recursive: true, force: true });

// 4. JavaScript bundle
const shim = (f) => path.join(HERE, "spa", "shims", f);
const js = await esbuild.build({
  entryPoints: [path.join(HERE, "spa", "main.tsx")],
  bundle: true,
  write: false,
  minify: true,
  format: "iife",
  target: ["es2022"],
  jsx: "automatic",
  legalComments: "none",
  define: { "process.env.NODE_ENV": '"production"' },
  nodePaths: [path.join(FRONT, "node_modules")],
  alias: {
    "next/link": shim("next-link.tsx"),
    "next/navigation": shim("next-navigation.ts"),
  },
  plugins: [
    {
      name: "monxuplan-browser",
      setup(b) {
        b.onResolve({ filter: /^@\/lib\/(loc|save)$/ }, (a) => ({ path: shim(a.path.split("/").pop() + ".ts") }));
        b.onResolve({ filter: /^\.\/(loc|save)$/ }, (a) => (a.importer.includes(path.join("frontend", "src", "lib")) ? { path: shim(a.path.slice(2) + ".ts") } : undefined));
        b.onResolve({ filter: /^@\// }, (a) => {
          const base = path.join(FRONT, "src", a.path.slice(2));
          for (const ext of ["", ".ts", ".tsx", "/index.ts", "/index.tsx"]) if (fs.existsSync(base + ext) && fs.statSync(base + ext).isFile()) return { path: base + ext };
          return undefined;
        });
        b.onLoad({ filter: /\.css$/ }, () => ({ contents: "", loader: "js" }));
      },
    },
  ],
});
const bundle = js.outputFiles[0].text;

const css = fontsCss() + (await tailwindCss()) + BOOT_CSS;

// 5. page (the artifact host wraps it in its own document skeleton)
const page = `<title>MonxuPlan</title>
<style>${css}</style>
<div id="monxuplan-root"></div>
<script>${bundle.replace(/<\/script/gi, "<\\/script")}</script>
`;
fs.writeFileSync(path.join(DIST, "index.html"), page);
fs.copyFileSync(path.join(HERE, "worker", "backend-worker.js"), path.join(DIST, "backend-worker.js"));

// 6. Pyodide runtime
for (const f of PYODIDE_FILES) fs.copyFileSync(path.join(PYODIDE, f), path.join(DIST, "pyodide", f));

// 7. Python packages
const wheels = path.join(CACHE, "wheels");
if (!fs.existsSync(wheels) || !fs.readdirSync(wheels).length) {
  fs.mkdirSync(wheels, { recursive: true });
  execFileSync(
    "pip",
    ["download", "--pre", "--only-binary=:all:", "--platform", "pyemscripten_2026_0_wasm32", "--platform", "any", "--python-version", "3.14", "--implementation", "cp", "--abi", "cp314", "--abi", "abi3", "--abi", "none", "-d", wheels, "-r", path.join(HERE, "requirements-browser.txt")],
    { stdio: "inherit" },
  );
}
execFileSync("python3", [path.join(HERE, "build_site.py"), wheels, path.join(PYODIDE, "python_stdlib.zip"), path.join(DIST, "py")], { stdio: "inherit" });

